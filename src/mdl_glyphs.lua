local cache = {}
-- grid(name, {a?, r, g, b} or {r, g, b, a}: same order as the panel colours {a, r, g, b})
function G.grid(name, color)
    local mask = G.MASKS[name]
    if not mask then return nil end
    local a, r, g, b = color[1], color[2], color[3], color[4]
    local key = name .. ':' .. a .. ',' .. r .. ',' .. g .. ',' .. b
    if cache[key] then return cache[key] end
    local runs = {}
    for y, row in ipairs(mask) do
        local x = 1
        while x <= #row do
            if row:sub(x, x) == '#' then
                local start = x
                while x <= #row and row:sub(x, x) == '#' do x = x + 1 end
                runs[#runs + 1] = {start - 1, y - 1, x - start, a, r, g, b}
            else
                x = x + 1
            end
        end
    end
    local grid = {w = #mask[1], h = #mask, runs = runs, id = key}
    cache[key] = grid
    return grid
end

return G
